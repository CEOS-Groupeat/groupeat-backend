CREATE OR REPLACE FUNCTION pg_temp.seed_terms(
    p_title VARCHAR,
    p_content TEXT,
    p_required BOOLEAN,
    p_type VARCHAR,
    p_target_type VARCHAR,
    p_version VARCHAR
) RETURNS VOID AS $$
BEGIN
    UPDATE terms
    SET active = false,
        updated_at = CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Seoul'
    WHERE target_type = p_target_type
      AND title = p_title
      AND active = true;

    INSERT INTO terms (
        title,
        content,
        required,
        type,
        target_type,
        version,
        active,
        created_at,
        updated_at
