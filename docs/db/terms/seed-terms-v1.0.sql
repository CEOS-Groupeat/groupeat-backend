② “업주”는 등록한 상품 정보가 실제 판매하는 상품과 일치하도록 성실히 관리하여야 하며, 재료 소진 등 판매 불가 사유가 발생한 경우 지체 없이 “플랫폼” 상 판매상태를 변경하여야 합니다.
③ “업주”는 상품의 메뉴 구성, 가격, 최소주문수량 등을 자율적으로 결정할 권한을 가지되, 관계 법령 및 회사의 운영정책을 위반할 수 없습니다.

## 제3장 그룹오더 접수 및 이행

**제6조 (주문의 접수)**
① “업주”는 “플랫폼”을 통해 전달되는 그룹오더 확정 내역을 지체 없이 확인하고, 정상적인 영업이 가능한 경우 이를 수락하여야 합니다.
② “업주”는 재료 소진, 영업 중단 등 정당한 사유가 있는 경우에 한하여 주문을 거절할 수 있으며, 거절 시 그 사유를 “플랫폼”을 통해 즉시 회사 및 “고객회원”에게 통지하여야 합니다.
③ “업주”는 정당한 사유 없이 반복적으로 주문을 지연, 거절 또는 임의 취소하여서는 안 되며, 이 경우 제9조에 따른 페널티 대상이 될 수 있습니다.

**제7조 (상품의 준비 및 픽업 제공)**
① “업주”는 그룹오더에서 지정된 픽업 일시에 맞추어 상품을 준비하여야 합니다.
② “업주”는 주문 내용과 동일한 상품을 위생적으로 포장하여 제공하여야 하며, 「식품위생법」 등 관계 법령이 정하는 위생 기준을 준수하여야 합니다.
③ “업주”의 귀책사유(조리 지연, 재료 소진에 따른 미제공, 주문 내용과 상이한 상품 제공 등)로 인해 “고객회원”에게 발생한 손해에 대하여는 “업주”가 책임을 부담합니다.

## 제4장 업주의 의무

**제8조 (업주의 의무)**
① “업주”는 관계 법령, 본 약관 및 회사가 공지하는 운영정책을 준수하여야 합니다.
② “업주”는 “고객회원”으로부터 제공받은 개인정보(연락처, 픽업 요청사항 등)를 주문 처리 목적 외로 사용하거나 제3자에게 제공하여서는 안 됩니다.
③ “업주”는 “고객회원”에게 회사를 통하지 않은 직거래를 유도하여서는 안 되며, 이에 관한 세부사항은 「플랫폼 외 직거래 금지 정책 동의」에 따릅니다.
④ “업주”는 정당한 사유 없이 “고객회원”의 리뷰 삭제·수정을 요구하거나, 리뷰 작성과 관련하여 “고객회원”에게 불이익을 고지하는 행위를 하여서는 안 됩니다.
⑤ “업주”는 회사 및 “고객회원”에게 폭언, 위협, 성희롱 등 부적절한 언행을 하여서는 안 됩니다.

**제9조 (이용제한 및 페널티)**
① 회사는 “업주”가 다음 각 호에 해당하는 경우, 경고, 노출순위 하향, 일시적 판매중단, 이용계약 해지 등의 조치를 취할 수 있습니다.
- 정당한 사유 없는 반복적 주문 거절·지연·임의취소
- 등록 상품과 실제 제공 상품의 현저한 불일치
- 위생 관련 법령 위반으로 행정처분을 받은 경우
- 본 약관 제8조에 따른 업주의 의무 위반
- 「플랫폼 외 직거래 금지 정책」 위반
- 그 밖에 「그루핏 서비스 이용약관」 제17조에 해당하는 경우

② 페널티의 세부 기준(경고 누적 횟수, 단계별 제재 내용 등)은 회사가 별도로 정하는 운영정책에 따릅니다.
③ “업주”는 이용제한 조치에 대하여 회사가 정한 절차에 따라 이의신청을 할 수 있습니다.

