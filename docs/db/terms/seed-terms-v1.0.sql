본 약관의 게시 및 개정에 관하여는 「그루핏 서비스 이용약관」 제3조를 준용합니다. 다만, “업주”에게 불리하거나 중대한 영향을 미치는 개정의 경우 적용일자 30일 전까지 “업주”에게 개별 통지합니다.

## 제2장 사업자회원 가입 및 입점

**제4조 (가입신청 및 심사)**
① “사업자서비스”를 이용하고자 하는 자는 사업자등록증, 대표자 신분증, 정산계좌 사본 등 회사가 요청하는 서류를 제출하여 가입을 신청하여야 합니다.
